"""The default Neon Coffee font, and the generator that renders it to a PNG.

Why a hand-drawn 8x8 font rather than a real typeface: at 320x240 a glyph is
about six pixels wide, and every antialiased edge a font renderer would produce
is a colour this palette cannot afford. Arcade boards drew their text from a
tile sheet for exactly this reason, and so do we.

The layout is fixed and the runtime relies on it:

    ASCII 32..95 -- space through underscore, uppercase only -- in a 32x2 grid
    of 8x8 cells, so the sheet is 256x16. Lowercase is folded to uppercase when
    drawn; there is no room for a second alphabet and arcade text was capitals
    anyway.

    That shape is not arbitrary. 256x16 is exactly the gap in VRAM between the
    two framebuffers and the texture slots, so the font costs no texture slot at
    all -- see the VRAM map in textures.py.

Glyphs occupy six columns and seven rows of each cell. The empty column and row
are the letter spacing, which is why text does not need kerning to be legible.

Run `python -m ncc font <out.png>` to regenerate the sheet.
"""

