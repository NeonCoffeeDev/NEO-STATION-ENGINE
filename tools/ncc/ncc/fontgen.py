LAST_CHAR = 95          # '_'
CHAR_COUNT = LAST_CHAR - FIRST_CHAR + 1


def sheet_size():
    rows = (CHAR_COUNT + COLUMNS - 1) // COLUMNS
    return COLUMNS * CELL_W, rows * CELL_H


def render(ink=(255, 255, 255)):
    """The font as a list of RGBA rows, transparent everywhere but the ink.

    Transparent rather than a black background because the PS1's one transparent
    colour is what lets text sit over artwork. A black-backed font would draw a
    box around every letter.
    """
    w, h = sheet_size()
    px = [[(0, 0, 0, 0)] * w for _ in range(h)]

    for code in range(FIRST_CHAR, LAST_CHAR + 1):
        ch = chr(code)
        rows = GLYPHS.get(ch)
        if rows is None:
            continue
        index = code - FIRST_CHAR
        ox = (index % COLUMNS) * CELL_W
        oy = (index // COLUMNS) * CELL_H
        for y, row in enumerate(rows):
            for x, cell in enumerate(row):
                if cell == "#":
                    px[oy + y][ox + x] = (ink[0], ink[1], ink[2], 255)
    return px


def write_png(path, ink=(255, 255, 255)):
    """Write the sheet with the standard library only -- no Pillow needed here."""
    import struct
    import zlib

    px = render(ink)
    h = len(px)
    w = len(px[0])

    raw = bytearray()
    for row in px:
        raw.append(0)                        # filter type 0: none
        for r, g, b, a in row:
            raw += bytes((r, g, b, a))

    def chunk(tag, data):
        return (struct.pack(">I", len(data)) + tag + data
                + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF))

    png = b"\x89PNG\r\n\x1a\n"
    png += chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0))
    png += chunk(b"IDAT", zlib.compress(bytes(raw), 9))
    png += chunk(b"IEND", b"")

    with open(path, "wb") as fh:
        fh.write(png)
    return w, h


def missing():
    """Characters in the range with no glyph -- they render as blanks."""
    return [chr(c) for c in range(FIRST_CHAR, LAST_CHAR + 1)
            if chr(c) not in GLYPHS]
